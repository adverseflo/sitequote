// SiteQuote frontend: generate a quote, edit it, export a PDF.
let quote = null;

const $ = (id) => document.getElementById(id);
const gbp = (n) => '£' + (Number(n) || 0).toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

// Same maths as src/totals.js
function computeTotals(q) {
  const materials = q.materials.reduce((s, m) => s + (+m.quantity || 0) * (+m.unit_price || 0), 0);
  const hours = q.tasks.reduce((s, t) => s + (+t.labour_hours || 0), 0);
  const labour = hours * (+q.labour_rate || 0);
  const subtotal = materials + labour;
  const vat = subtotal * (+q.vat_rate || 0);
  return { materials, labour_hours: hours, labour, subtotal, vat, total: subtotal + vat };
}

fetch('/api/health').then((r) => r.json()).then((h) => {
  $('labour-rate').value = h.labour_rate;
  if (h.mock) { $('mode').textContent = 'Mock mode: sample data'; $('mode').hidden = false; }
}).catch(() => {});

$('job-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  const description = $('description').value.trim();
  if (description.length < 10) return setStatus('Describe the job in a bit more detail.', true);

  $('go').disabled = true;
  setStatus('Working out tasks and materials, then checking live prices… this can take 20–40 seconds.');
  try {
    const res = await fetch('/api/quote', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ description, labour_rate: +$('labour-rate').value }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || 'Something went wrong');
    quote = data;
    render();
    setStatus('');
  } catch (err) {
    setStatus(err.message, true);
  } finally {
    $('go').disabled = false;
  }
});

$('labour-rate').addEventListener('input', () => {
  if (!quote) return;
  quote.labour_rate = +$('labour-rate').value || 0;
  renderTasks();
  renderTotals();
});

function setStatus(msg, isError = false) {
  $('status').textContent = msg;
  $('status').className = isError ? 'error' : '';
}

function render() {
  $('result').hidden = false;
  $('summary').textContent = quote.summary || 'Quote';
  $('assumptions').innerHTML = '';
  (quote.assumptions || []).forEach((a) => {
    const li = document.createElement('li');
    li.textContent = a;
    $('assumptions').append(li);
  });
  $('assumptions-box').hidden = !(quote.assumptions || []).length;
  renderMaterials();
  renderTasks();
  renderTotals();
  const secs = (quote.elapsed_ms / 1000).toFixed(1);
  $('meta').textContent = quote.model === 'mock' ? 'Sample data (mock mode)' : `Generated by ${quote.model} in ${secs}s`;
}

function input(value, onChange, type = 'text') {
  const el = document.createElement('input');
  el.type = type;
  if (type === 'number') { el.step = 'any'; el.min = '0'; }
  el.value = value;
  el.addEventListener('input', () => { onChange(type === 'number' ? +el.value || 0 : el.value); renderTotals(); });
  return el;
}

function cell(row, content, cls) {
  const td = document.createElement('td');
  if (cls) td.className = cls;
  if (content instanceof Node) td.append(content); else td.textContent = content;
  row.append(td);
  return td;
}

function removeBtn(onClick) {
  const b = document.createElement('button');
  b.type = 'button'; b.className = 'x'; b.textContent = '✕'; b.setAttribute('aria-label', 'Remove');
  b.addEventListener('click', onClick);
  return b;
}

function renderMaterials() {
  const body = $('materials');
  body.innerHTML = '';
  quote.materials.forEach((m, i) => {
    const tr = document.createElement('tr');
    let amount;
    const update = () => { amount.textContent = gbp(m.quantity * m.unit_price); };
    cell(tr, input(m.name, (v) => { m.name = v; }));
    cell(tr, input(m.quantity, (v) => { m.quantity = v; update(); }, 'number'));
    cell(tr, input(m.unit, (v) => { m.unit = v; }));
    cell(tr, input(m.unit_price, (v) => { m.unit_price = v; update(); }, 'number'));
    amount = cell(tr, '', 'num');
    update();
    if (m.source && m.source.startsWith('http')) {
      const a = document.createElement('a');
      a.href = m.source; a.target = '_blank'; a.rel = 'noopener';
      a.textContent = new URL(m.source).hostname.replace(/^www\./, '');
      a.title = m.note || '';
      cell(tr, a);
    } else {
      cell(tr, m.source || '');
    }
    cell(tr, removeBtn(() => { quote.materials.splice(i, 1); renderMaterials(); renderTotals(); }));
    body.append(tr);
  });
}

function renderTasks() {
  const body = $('tasks');
  body.innerHTML = '';
  quote.tasks.forEach((t, i) => {
    const tr = document.createElement('tr');
    let amount;
    const update = () => { amount.textContent = gbp(t.labour_hours * quote.labour_rate); };
    cell(tr, input(t.name, (v) => { t.name = v; }));
    cell(tr, input(t.labour_hours, (v) => { t.labour_hours = v; update(); }, 'number'));
    amount = cell(tr, '', 'num');
    update();
    cell(tr, removeBtn(() => { quote.tasks.splice(i, 1); renderTasks(); renderTotals(); }));
    body.append(tr);
  });
}

function renderTotals() {
  const t = computeTotals(quote);
  const vatPct = Math.round(quote.vat_rate * 100);
  $('totals').innerHTML = '';
  [
    ['Materials', t.materials],
    [`Labour (${t.labour_hours} h)`, t.labour],
    ['Subtotal', t.subtotal],
    [`VAT (${vatPct}%)`, t.vat],
    ['Total', t.total, true],
  ].forEach(([label, value, grand]) => {
    const dt = document.createElement('dt'); dt.textContent = label;
    const dd = document.createElement('dd'); dd.textContent = gbp(value);
    if (grand) { dt.className = 'grand'; dd.className = 'grand'; }
    $('totals').append(dt, dd);
  });
}

$('add-material').addEventListener('click', () => {
  quote.materials.push({ name: '', quantity: 1, unit: 'each', unit_price: 0, source: 'manual' });
  renderMaterials(); renderTotals();
});
$('add-task').addEventListener('click', () => {
  quote.tasks.push({ name: '', labour_hours: 1 });
  renderTasks(); renderTotals();
});

$('pdf').addEventListener('click', async () => {
  const body = { ...quote, business_name: $('business-name').value.trim(), client_name: $('client-name').value.trim() };
  const res = await fetch('/api/pdf', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  if (!res.ok) return setStatus('Could not make the PDF.', true);
  const blob = await res.blob();
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = 'quote.pdf'; a.click();
  URL.revokeObjectURL(url);
});
